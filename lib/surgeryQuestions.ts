export function getQuestionCountByTopic(): Record<SurgeryTopic, number> {
  const counts = {} as Record<SurgeryTopic, number>;
  (Object.keys(SURGERY_TOPIC_LABELS) as SurgeryTopic[]).forEach((t) => (counts[t] = 0));
  surgeryQuestions.forEach((q) => {
    counts[q.topic] = (counts[q.topic] ?? 0) + 1;
  });
  return counts;
}

export function getQuestionsByTopics(topics: SurgeryTopic[], n: number): SurgeryQuestion[] {
  const pool = surgeryQuestions.filter((q) => topics.includes(q.topic));
  const shuffled = [...pool];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled.slice(0, Math.min(n, shuffled.length));
}
