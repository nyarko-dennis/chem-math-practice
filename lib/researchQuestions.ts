export function getQuestionsByTopics(
  topics: ResearchTopic[],
  count: number,
): ResearchQuestion[] {
  const pool = researchQuestions.filter((q) => topics.includes(q.topic));
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}

export function getQuestionCountByTopic(): Record<ResearchTopic, number> {
  const counts: Record<string, number> = {};
  researchQuestions.forEach((q) => {
    counts[q.topic] = (counts[q.topic] || 0) + 1;
  });
  return counts as Record<ResearchTopic, number>;
}
